# Current locale in memory
_current_locale = "uz"

def set_locale(locale_str: str):
    """Sets active locale code, e.g. 'uz', 'en', or 'ru'."""
    global _current_locale
    if not locale_str:
        return
    l_str = locale_str.lower()
    if "en" in l_str or "english" in l_str:
        _current_locale = "en"
    elif "ru" in l_str or "russian" in l_str or "русск" in l_str:
        _current_locale = "ru"
    elif "uz" in l_str or "uzbek" in l_str:
        _current_locale = "uz"
    else:
        _current_locale = "uz"
    logger.info(f"UI Locale set to: {_current_locale}")

def get_locale() -> str:
    """Returns currently active locale code."""
    return _current_locale

def t(key: str, default: str = None) -> str:
    """
    Translates key to current locale.
    Fallback to default value, or key string itself.
    """
    locale_dict = TRANSLATIONS.get(_current_locale, TRANSLATIONS["uz"])
    return locale_dict.get(key, default or key)
